#!/usr/bin/env python3
"""Generate tests/runtime_bodies.txt from plugin/HairFlow.txt.

ZBrush cannot IPress a ZScript button from another script and keep going: the
pressed button takes over and the caller stops. So this generator copies each
HairFlow button's command block *verbatim* out of HairFlow.txt and runs the
blocks in sequence inside one test macro, reading the native Stroke state back
after each block. Same source text, same paths, same routines.

Run:  python tests/build_runtime_test.py
Then: put tests/runtime_bodies.txt (and plugin/HairFlow.txt, so the slider
exists) into ZStartup/Macros/<folder>/, start ZBrush 2025, read
C:/HairFlow/runtime_bodies.txt.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "plugin" / "HairFlow.txt"
OUT = ROOT / "tests" / "runtime_bodies.txt"

STEPS = [
    "Remember Stroke",
    "Preflight Check",
    "Long Strand Curve",
    "Step Fine",
    "Step Fast",
    "Curve Snap Off",
    "Curve Snap On",
    "Step Medium",
    "Freehand Assist",
    "Reset Stroke Defaults",
    "Long Strand Curve",
    "Curve Off",
    "Step Standard",
    "Diagnostics",
    "Shape Lock",
    "Shape Lock",
    "Shape Unlock",
    "Shape Lock",
    "Restore Stroke",
]


def split_top_level(s: str) -> list[str]:
    """Split s on commas that are outside brackets, parens and quotes."""
    parts, depth, cur, quote = [], 0, [], False
    for ch in s:
        if ch == '"':
            quote = not quote
        if not quote:
            if ch in "[(":
                depth += 1
            elif ch in "])":
                depth -= 1
            elif ch == "," and depth == 0:
                parts.append("".join(cur))
                cur = []
                continue
        cur.append(ch)
    parts.append("".join(cur))
    return parts


def extract(text: str) -> tuple[list[str], dict[str, str]]:
    # strip // comments (outside strings is enough for this ASCII source)
    lines = [ln for ln in text.splitlines() if not ln.lstrip().startswith("//")]
    text = "\n".join(lines)
    blocks, i = [], 0
    while True:
        j = text.find("[", i)
        if j < 0:
            break
        depth, quote, k = 0, False, j
        while k < len(text):
            ch = text[k]
            if ch == '"':
                quote = not quote
            elif not quote:
                if ch == "[":
                    depth += 1
                elif ch == "]":
                    depth -= 1
                    if depth == 0:
                        break
            k += 1
        blocks.append(text[j:k + 1])
        i = k + 1
    prelude, bodies = [], {}
    for b in blocks:
        head = b[1:].split(",", 1)[0].strip()
        if head in ("VarDef", "RoutineDef"):
            prelude.append(b)
        elif head == "IButton":
            args = split_top_level(b[1:-1])
            name = args[1].strip().strip('"').split(":")[-1]
            bodies[name] = args[3].strip()
    return prelude, bodies


def main() -> int:
    prelude, bodies = extract(SRC.read_text(encoding="ascii"))
    out = [
        "[IConfig, 2021]",
        "// GENERATED by tests/build_runtime_test.py from plugin/HairFlow.txt - do not edit",
        *prelude,
        '[VarDef, rtL, ""]', "[VarDef, rtO, 0]", "[VarDef, rtN, 0]",
        "[RoutineDef, rtW,",
        "  [VarSet, rtN, [StrLength, rtL]]",
        "  [MemWriteString, RTM, rtL, rtO, 0]",
        "  [VarSet, rtO, rtO + rtN]",
        "  [MemWriteString, RTM, [StrFromAsc, 10], rtO, 0]",
        "  [VarSet, rtO, rtO + 1]",
        '  [MemSaveToFile, RTM, "C:/HairFlow/runtime_bodies.txt", 1]',
        "]",
        "[RoutineDef, rtState,",
        '  [VarSet, rtL, [StrMerge, "   mode=", [IGet, "Stroke:Curve:Curve Mode"], " step=", [IGet, "Stroke:Curve:Curve Step"], " slider=", [IGet, "ZPlugin:HairFlow:Curve Step"], " snap=", [IGet, "Stroke:Curve:Snap"]]]',
        "  [RoutineCall, rtW]",
        '  [VarSet, rtL, [StrMerge, "   lazy=", [IGet, "Stroke:Lazy Mouse"], " rad=", [IGet, "Stroke:Lazy Radius"], " lstep=", [IGet, "Stroke:Lazy Step"], " lsm=", [IGet, "Stroke:Lazy Smooth"]]]',
        "  [RoutineCall, rtW]",
        '  [VarSet, rtL, [StrMerge, "   zadd=", [IGet, "Draw:Zadd"], " zsub=", [IGet, "Draw:Zsub"], " zint=", [IGet, "Draw:Z Intensity"], " lock=", hfLocked, " rem=", hfHasSnap]]',
        "  [RoutineCall, rtW]",
        "]",
        "[If, 1,",
        "[MemCreate, RTM, 20000, 0]",
        '[VarSet, rtL, [StrMerge, "pal=", [IExists, "ZPlugin:HairFlow"], " slider=", [IExists, "ZPlugin:HairFlow:Curve Step"]]]',
        "[RoutineCall, rtW]",
        '[VarSet, rtL, "start"]',
        "[RoutineCall, rtW]",
        "[RoutineCall, rtState]",
    ]
    for step in STEPS:
        out.append(f'[VarSet, rtL, "body {step}"]')
        out.append("[RoutineCall, rtW]")
        out.append(bodies[step])
        out.append("[RoutineCall, rtState]")
    extras = [
        ("slider ISet 0.6 (native step should follow)",
         '[ISet, "ZPlugin:HairFlow:Curve Step", 0.6]'),
        ("legacy 1.4.0 Long Strand body: ISet Stroke:Curve 1 (sub-palette, not Curve Mode)",
         '[ISet, "Stroke:Curve", 1]'),
        ("legacy 1.4.0 Add path resolves to", ""),
        ("restore user state again", bodies["Restore Stroke"]),
    ]
    for label, body in extras:
        out.append(f'[VarSet, rtL, "extra {label}"]')
        out.append("[RoutineCall, rtW]")
        if label.startswith("legacy 1.4.0 Add"):
            out.append('[VarSet, rtL, [StrMerge, "   ", [IGetTitle, "Stroke:Curve Functions:Add", 1], " subpal=", [IGet, "Stroke:Curve"]]]')
            out.append("[RoutineCall, rtW]")
            out.append('[ISet, "Stroke:Curve", 0]')
        else:
            out.append(body)
        out.append("[RoutineCall, rtState]")
    out += ['[VarSet, rtL, "done"]', "[RoutineCall, rtW]", "[MemDelete, RTM]", "]", ""]
    OUT.write_text("\r\n".join(out), encoding="ascii")
    print(f"wrote {OUT} ({len(STEPS)} steps, {len(bodies)} buttons parsed)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
